// Bundles index.html + css/ + js/ + photos/ into one file (dist/chillcheck.html) so the app
// can be shared as a single page. Also refreshes js/photos.js so index.html sees new photos.
// Run: node build.js
const fs = require("fs");
const path = require("path");

const root = __dirname;
const read = file => fs.readFileSync(path.join(root, file), "utf8");

// Photos in photos/ stand in for the fridge camera
const IMAGE_TYPES = { ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp", ".gif": "image/gif" };
const photoDir = path.join(root, "photos");
const photos = fs.existsSync(photoDir)
  ? fs.readdirSync(photoDir).filter(f => IMAGE_TYPES[path.extname(f).toLowerCase()]).sort()
  : [];
const manifest = list => `// Generated by build.js from the photos/ folder. Do not edit by hand.\nconst CAMERA_PHOTOS = ${JSON.stringify(list, null, 2)};\n`;

// Local version links to the files; the bundle embeds them, since a shared page can't read your folder
fs.writeFileSync(path.join(root, "js", "photos.js"), manifest(photos.map(f => ({ name: f, src: `photos/${f}` }))));
const embeddedPhotos = manifest(photos.map(f => ({
  name: f,
  src: `data:${IMAGE_TYPES[path.extname(f).toLowerCase()]};base64,${fs.readFileSync(path.join(photoDir, f)).toString("base64")}`
})));

const html = read("index.html");
const head = html.match(/<head>([\s\S]*?)<\/head>/)[1]
  .replace(/<meta charset[^>]*>\s*/, "")
  .replace(/<meta name="viewport"[^>]*>\s*/, "");
const body = html.match(/<body>([\s\S]*?)<\/body>/)[1];

const inline = s => s
  .replace(/<link rel="stylesheet" href="(css\/[^"]+)">/g, (_, file) => `<style>\n${read(file)}</style>`)
  .replace(/<script src="(js\/[^"]+)"><\/script>/g, (_, file) =>
    `<script>\n${file === "js/photos.js" ? embeddedPhotos : read(file)}</script>`);

const out = `${inline(head).trim()}\n${inline(body).trim()}\n`;
fs.mkdirSync(path.join(root, "dist"), { recursive: true });
fs.writeFileSync(path.join(root, "dist", "chillcheck.html"), out);

const mb = Buffer.byteLength(out) / 1024 / 1024;
console.log(`Built dist/chillcheck.html (${mb.toFixed(1)} MB, ${photos.length} photo${photos.length === 1 ? "" : "s"}: ${photos.join(", ") || "none"})`);
if (mb > 15) console.warn("Warning: over 15 MB. The shared page limit is 16 MB, so use smaller photos.");
