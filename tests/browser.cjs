// Run with Playwright installed outside the app; never required to start ChillCheck.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(catalog=>{window.testCatalog=catalog;},require('../supabase/mock-catalog.json'));
 await page.addInitScript({path:path.join(__dirname,'mock-backend.js')});
 await page.goto(process.env.APP_URL || 'http://127.0.0.1:8081/');
 await page.getByLabel('Email',{exact:true}).fill('tester@example.invalid');
 await page.getByLabel('Password',{exact:true}).fill('test-only-password');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByRole('button',{name:'Create fridge',exact:true}).click();
 await page.getByLabel('Your fridge',{exact:true}).selectOption(await page.evaluate(()=>window.testDB.fridges[0].id));
 await page.getByRole('button',{name:'+ Add food',exact:true}).click();
 await page.getByLabel('Food name',{exact:true}).fill('Tomatoes');
 await page.getByLabel('Quantity',{exact:true}).fill('6 pcs');
 await page.getByLabel('Expiry date (leave blank if unknown)',{exact:true}).fill('2030-01-01');
 await page.getByRole('button',{name:'Save food',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 await page.getByRole('button',{name:'Try example scan',exact:true}).click();
 await page.getByRole('button',{name:'Confirm and save',exact:true}).click();
 await page.getByRole('heading',{name:'Eat Me First',exact:true}).waitFor();
 const saved=await page.evaluate(()=>window.testDB.food_items.find(i=>i.name==='Rice-stuffed peppers'));
 if(saved.photo_key!=='stuffed-peppers')throw Error('Photo reference was not saved');
 await page.locator('#type-cooked').click();
 await page.getByRole('heading',{name:'Rice-stuffed peppers',exact:true}).waitFor();
 await page.screenshot({path:'/tmp/react-fridge.png',fullPage:true});
 const soup=page.locator('article').filter({has:page.getByRole('heading',{name:'Leftover vegetable soup',exact:true})});
 await soup.getByRole('button',{name:'Edit',exact:true}).click();
 await page.getByLabel('Quantity',{exact:true}).fill('3 portions');
 await page.evaluate(()=>window.testFail=true);
 await page.getByRole('button',{name:'Save food',exact:true}).click();
 await page.getByText('Simulated write failure',{exact:true}).first().waitFor();
 if(await page.getByRole('dialog').count()!==1)throw Error('Failed edit closed the form');
 await page.evaluate(()=>window.testFail=false);
 await page.getByRole('button',{name:'Save food',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 await soup.getByRole('button',{name:'Eaten',exact:true}).click();
 await page.getByText('Marked as eaten.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'History',exact:true}).click();
 await page.getByRole('heading',{name:'Leftover vegetable soup',exact:true}).waitFor();
 await page.getByRole('button',{name:'Recipes',exact:true}).click();
 await page.locator('.recipe-photo img').evaluateAll(async images=>await Promise.all(images.map(img=>{img.loading='eager';return img.decode()})));
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/react-recipes-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.getByRole('button',{name:'Food & you',exact:true}).click();
 await page.getByRole('heading',{name:'Food & your body',exact:true}).waitFor();
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.getByRole('heading',{name:'Welcome back',exact:true}).waitFor();
 await page.screenshot({path:'/tmp/react-auth-mobile.png',fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: sign-in, fridge creation, add/edit, scan review, filters, failed-write recovery, eaten/history, recipes, mobile, sign-out.');
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
